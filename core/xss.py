import requests

from domain.models import Finding, FindingType
from gpt import client, prompts
from core import settings


def test(url: str):
    """
    Test for reflected XSS on a target URL by sending payloads via the 'q'
    parameter and checking whether they are reflected in the response.

    Payloads are generated by the Groq LLM, with a static fallback from
    config.yaml if the LLM returns nothing.

    Returns:
        list[Finding]: XSS or error findings.
    """
    payloads = client.generate_payloads(prompts.xss_prompt(url))
    if not payloads:
        payloads = settings.load().get("xss_payloads", [])

    timeout = settings.request_timeout()
    findings = []

    for payload in payloads:
        target = f"{url}?q={payload}"
        try:
            r = requests.get(target, timeout=timeout)
            if payload in r.text:
                findings.append(
                    Finding(
                        type=FindingType.XSS,
                        detail="Posible XSS reflejado: el payload se refleja en la respuesta",
                        url=target,
                        payload=payload,
                    )
                )
        except Exception as e:
            findings.append(
                Finding(
                    type=FindingType.ERROR,
                    detail=f"Error al probar XSS: {e}",
                    url=target,
                    payload=payload,
                )
            )

    return findings
